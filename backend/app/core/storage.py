"""File storage, behind one interface (Phase 3 shared groundwork).

The platform stored no files before Phase 3. Cloud Run's disk is ephemeral and per
instance, so an upload written there would vanish on the next deploy — or simply not exist
on the instance that serves the download. Production therefore writes to a private Google
Cloud Storage bucket; development and tests write to a local folder.

The provider is chosen from settings, following the pattern of ``notifications/email.py``,
and tests swap in their own with ``set_storage``. Nothing outside this module knows which
one is in use: callers ``put`` bytes under a key and later ask for a ``signed_url``. A
provider that cannot sign (local disk) returns ``None``, and the download route streams the
bytes itself instead.

**Keys are never the user's file name.** They are ``{institute_id}/{purpose}/{uuid}``, built
by the files service. A name chosen by a user is how path traversal and overwrites happen.
"""

from __future__ import annotations

import logging
from abc import ABC, abstractmethod
from datetime import timedelta
from pathlib import Path

from app.core.config import settings

logger = logging.getLogger(__name__)


class StorageProvider(ABC):
    @abstractmethod
    async def put(self, key: str, data: bytes, content_type: str) -> None: ...

    @abstractmethod
    async def open(self, key: str) -> bytes: ...

    @abstractmethod
    async def signed_url(self, key: str, *, ttl_seconds: int, filename: str) -> str | None:
        """A short-lived link to the object, or ``None`` if this provider cannot sign."""


class LocalStorage(StorageProvider):
    """A folder on disk. Development and tests only — never production."""

    def __init__(self, root: str | Path) -> None:
        self.root = Path(root).resolve()

    def _path(self, key: str) -> Path:
        # Keys are generated by the files service, but the check is cheap and a key that
        # escaped the root would be a read of any file the process can see.
        path = (self.root / key).resolve()
        if not path.is_relative_to(self.root):
            raise ValueError("storage key escapes the storage root")
        return path

    async def put(self, key: str, data: bytes, content_type: str) -> None:
        import anyio

        path = self._path(key)
        await anyio.to_thread.run_sync(lambda: _write(path, data))

    async def open(self, key: str) -> bytes:
        import anyio

        path = self._path(key)
        return await anyio.to_thread.run_sync(path.read_bytes)

    async def signed_url(self, key: str, *, ttl_seconds: int, filename: str) -> str | None:
        return None


def _write(path: Path, data: bytes) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(data)


class GcsStorage(StorageProvider):
    """A private GCS bucket. Objects are never public; downloads use V4 signed URLs.

    The client library is synchronous, so every call runs off the event loop. It is
    imported lazily so tests and local development do not need Google credentials.

    Signing on Cloud Run has no private key file to hand: the service account signs
    through the IAM ``signBlob`` API, which is why the deployment needs
    ``roles/iam.serviceAccountTokenCreator`` on itself (see DEPLOYMENT.md).
    """

    def __init__(self, bucket: str) -> None:
        self.bucket_name = bucket
        self._bucket = None

    def _get_bucket(self):
        if self._bucket is None:
            from google.cloud import storage  # type: ignore[import-untyped]

            self._bucket = storage.Client().bucket(self.bucket_name)
        return self._bucket

    async def put(self, key: str, data: bytes, content_type: str) -> None:
        import anyio

        blob = self._get_bucket().blob(key)
        await anyio.to_thread.run_sync(
            lambda: blob.upload_from_string(data, content_type=content_type)
        )

    async def open(self, key: str) -> bytes:
        import anyio

        blob = self._get_bucket().blob(key)
        return await anyio.to_thread.run_sync(blob.download_as_bytes)

    async def signed_url(self, key: str, *, ttl_seconds: int, filename: str) -> str | None:
        import anyio

        blob = self._get_bucket().blob(key)

        def sign() -> str:
            import google.auth
            from google.auth.transport import requests as google_requests

            credentials, _ = google.auth.default()
            credentials.refresh(google_requests.Request())
            # Credentials from the metadata server carry no private key. Passing the
            # service account email and an access token makes the library sign through
            # IAM instead of failing with "you need a private key to sign credentials".
            return blob.generate_signed_url(
                version="v4",
                expiration=timedelta(seconds=ttl_seconds),
                method="GET",
                response_disposition=f'inline; filename="{filename}"',
                service_account_email=getattr(credentials, "service_account_email", None),
                access_token=credentials.token,
            )

        return await anyio.to_thread.run_sync(sign)


def _default_storage() -> StorageProvider:
    if settings.storage_backend == "gcs":
        if not settings.gcs_bucket:
            raise RuntimeError("STORAGE_BACKEND=gcs needs GCS_BUCKET; see backend/.env.example.")
        return GcsStorage(settings.gcs_bucket)
    if settings.is_production:
        # A local folder on Cloud Run loses every upload on the next deploy. Refuse loudly
        # rather than accept files that will silently disappear.
        raise RuntimeError("Production must use STORAGE_BACKEND=gcs.")
    return LocalStorage(settings.local_storage_dir)


_storage: StorageProvider | None = None


def get_storage() -> StorageProvider:
    global _storage
    if _storage is None:
        _storage = _default_storage()
    return _storage


def set_storage(provider: StorageProvider | None) -> None:
    """Used by tests. Not reachable from any HTTP route."""
    global _storage
    _storage = provider
